import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';

const browser = await chromium.launch({ executablePath: process.env.NOVA_CHROMIUM_PATH === 'managed' ? undefined : process.env.NOVA_CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const api = process.env.NOVA_API_TEST_URL || 'http://127.0.0.1:8777/api';
  const errors = [];
  let executableRequests = 0;
  page.on('pageerror', (error) => errors.push(error.message));
  page.on('request', (request) => { if (request.method() === 'POST' && (/\/adapters\/pywake\/(probe|configure)$/.test(request.url()) || request.url().endsWith('/external-runs'))) executableRequests += 1; });
  const savedCases = async () => (await page.request.get(`${api}/v1/external-cases`)).json();
  const getCase = async (id) => (await page.request.get(`${api}/v1/external-cases/${id}`)).json();
  const saveCopy = async () => {
    const response = page.waitForResponse((item) => item.url().endsWith('/v1/external-cases') && item.request().method() === 'POST');
    await page.getByRole('button', { name: 'Save case copy', exact: true }).click();
    const result = await response;
    assert.ok(result.ok(), await result.text());
    const asset = await result.json();
    await page.getByRole('combobox', { name: 'Saved wind farm case', exact: true }).locator(`option[value="${asset.id}"]`).waitFor({ state: 'attached' });
    await page.waitForFunction((id) => document.querySelector('[aria-label="Saved wind farm case"]')?.value === id, asset.id);
    return asset;
  };
  const openIntegrations = async () => page.getByRole('navigation', { name: 'Workspace navigation' }).getByRole('button', { name: 'Integrations', exact: true }).click();
  await page.goto(process.env.NOVA_UI_TEST_URL || 'http://127.0.0.1:5174');
  await openIntegrations();
  await page.getByRole('combobox', { name: 'External adapter', exact: true }).selectOption('pywake');
  const softwarePath = '/not-installed/example-pywake-env/bin/python';
  await page.getByRole('textbox', { name: 'Python environment interpreter', exact: true }).fill(softwarePath);
  assert.equal(await page.getByRole('combobox', { name: 'Execution environment', exact: true }).inputValue(), 'python_environment');
  await page.getByRole('img', { name: 'Wind farm layout preview', exact: true }).waitFor();
  await page.getByRole('textbox', { name: 'Case name', exact: true }).fill('Browser wind farm reference');
  await page.getByRole('textbox', { name: 'Case notes', exact: true }).fill('Synthetic two-turbine reference');
  assert.equal(await page.getByRole('checkbox', { name: 'Case contains demonstration data', exact: true }).isChecked(), true);
  const first = await saveCopy();
  assert.equal(first.demonstration, true);
  assert.equal(first.case.layout.x_m[1], 500);
  assert.equal(first.notes, 'Synthetic two-turbine reference');
  await page.getByRole('spinbutton', { name: 'Turbine 2 x [m]', exact: true }).fill('750');
  await page.getByRole('textbox', { name: 'Case name', exact: true }).fill('Browser wind farm 750m copy');
  await page.getByRole('textbox', { name: 'Case notes', exact: true }).fill('750m layout copy');
  const second = await saveCopy();
  assert.notEqual(second.id, first.id);
  assert.equal(second.case.layout.x_m[1], 750);
  assert.equal((await getCase(first.id)).case.layout.x_m[1], 500);
  assert.equal((await getCase(first.id)).case_hash, first.case_hash);
  // Choosing an asset is separate from explicitly replacing the draft inputs.
  await page.getByRole('spinbutton', { name: 'Turbine 2 x [m]', exact: true }).fill('999');
  await page.getByRole('combobox', { name: 'Saved wind farm case', exact: true }).selectOption(first.id);
  assert.equal(await page.getByRole('spinbutton', { name: 'Turbine 2 x [m]', exact: true }).inputValue(), '999');
  await page.getByRole('button', { name: 'Load saved case (replace inputs)', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Loaded saved inputs: Browser wind farm reference.' }).waitFor();
  assert.equal(await page.getByRole('spinbutton', { name: 'Turbine 2 x [m]', exact: true }).inputValue(), '500');
  assert.equal(await page.getByRole('textbox', { name: 'Python environment interpreter', exact: true }).inputValue(), softwarePath);
  // A partially edited layout must not draw an invented turbine at the origin.
  await page.getByRole('button', { name: 'Add turbine', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Empty coordinates are not interpreted as zero.' }).waitFor();
  assert.equal(await page.getByRole('img', { name: 'Wind farm layout preview', exact: true }).count(), 0);
  await page.getByRole('spinbutton', { name: 'Turbine 3 x [m]', exact: true }).fill('-250');
  await page.getByRole('spinbutton', { name: 'Turbine 3 y [m]', exact: true }).fill('300');
  await page.getByRole('img', { name: 'Turbine 3: East -250 m, North 300 m', exact: true }).waitFor();
  const markers = await page.getByRole('img', { name: 'Wind farm layout preview', exact: true }).locator('circle').evaluateAll((nodes) => nodes.map((circle) => ({ x: Number(circle.getAttribute('cx')), y: Number(circle.getAttribute('cy')) })));
  const xScale = (markers[1].x - markers[0].x) / 500;
  const yScale = (markers[0].y - markers[2].y) / 300;
  assert.ok(Math.abs(xScale - yScale) < 1e-10, 'East and North must use equal physical distance scales');
  await page.getByRole('button', { name: 'Load saved case (replace inputs)', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('[aria-label="Turbine 3 x [m]"]'));
  await page.getByRole('spinbutton', { name: 'Turbine 2 x [m]', exact: true }).fill('650');
  await page.getByRole('textbox', { name: 'Case notes', exact: true }).fill('Unsaved navigation draft');
  await page.getByRole('navigation', { name: 'Workspace navigation' }).getByRole('button', { name: 'Studies', exact: true }).click();
  await openIntegrations();
  await page.getByRole('textbox', { name: 'Python environment interpreter', exact: true }).waitFor();
  assert.equal(await page.getByRole('combobox', { name: 'External adapter', exact: true }).inputValue(), 'pywake');
  assert.equal(await page.getByRole('spinbutton', { name: 'Turbine 2 x [m]', exact: true }).inputValue(), '650');
  assert.equal(await page.getByRole('textbox', { name: 'Case notes', exact: true }).inputValue(), 'Unsaved navigation draft');
  assert.equal(await page.getByRole('textbox', { name: 'Python environment interpreter', exact: true }).inputValue(), softwarePath);
  await page.reload();
  await openIntegrations();
  await page.getByRole('combobox', { name: 'External adapter', exact: true }).selectOption('pywake');
  await page.getByRole('combobox', { name: 'Saved wind farm case', exact: true }).locator(`option[value="${first.id}"]`).waitFor({ state: 'attached' });
  await page.getByRole('combobox', { name: 'Saved wind farm case', exact: true }).selectOption(first.id);
  await page.getByRole('button', { name: 'Load saved case (replace inputs)', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Loaded saved inputs: Browser wind farm reference.' }).waitFor();
  assert.equal(await page.getByRole('spinbutton', { name: 'Turbine 2 x [m]', exact: true }).inputValue(), '500');
  assert.equal(await page.getByRole('textbox', { name: 'Case notes', exact: true }).inputValue(), first.notes);
  const beforeInvalid = (await savedCases()).map((asset) => asset.id).sort();
  await page.getByRole('textbox', { name: 'Wind probabilities', exact: true }).fill('[[0.2, 0.2]]');
  await page.getByRole('button', { name: 'Save case copy', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'Wind probabilities must sum to 1' }).waitFor();
  assert.deepEqual((await savedCases()).map((asset) => asset.id).sort(), beforeInvalid);
  assert.equal((await getCase(first.id)).case_hash, first.case_hash);
  assert.equal((await getCase(second.id)).case_hash, second.case_hash);
  assert.equal(executableRequests, 0, 'Case management must not probe or launch independently installed PyWake');
  const screenshots = new URL('../../.desktop-tools/ui-navigation/external-cases/', import.meta.url);
  await mkdir(screenshots, { recursive: true });
  await page.getByRole('img', { name: 'Wind farm layout preview', exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: fileURLToPath(new URL('saved-pywake-case-1440.png', screenshots)), animations: 'disabled' });
  assert.deepEqual(errors, []);
  console.log('Saved PyWake cases passed without an installation: immutable copies, explicit load, persisted cases, navigation draft, validation and equal-scale layout preview.');
} finally { await browser.close(); }
